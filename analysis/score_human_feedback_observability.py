"""Held-out-cell pilot for mechanistic feedback observability.

The forward cohort is generated by human_feedback_observability_cohort.m.
All reported errors are synthetic in-model errors; this is not human-data validation.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy.spatial.distance import cdist

ROOT = Path(__file__).resolve().parent / "human_bidirectional_output"
DATA = ROOT / "feedback_observability_cohort.csv"
OUT = ROOT / "feedback_observability_score.json"
TWIN_INPUT = ROOT / "feedback_native_twin_input.csv"


def feature_sets(a: np.ndarray) -> dict[str, np.ndarray]:
    early = a[:, 6:18]
    late = a[:, 18:30]
    ap_ca = [0, 1, 2, 3, 4, 8, 9, 10, 11]
    return {
        "rest_AP_Ca": a[:, 3:5],
        "rest_AP_Ca_T": a[:, 3:6],
        "early_AP_Ca": np.c_[a[:, 3:5], early[:, ap_ca]],
        "early_AP_Ca_T": np.c_[a[:, 3:6], early],
        "late_AP_Ca": np.c_[a[:, 3:5], late[:, ap_ca]],
        "late_AP_Ca_T": np.c_[a[:, 3:6], late],
        "early_late_AP_Ca": np.c_[a[:, 3:5], early[:, ap_ca], late[:, ap_ca]],
        "early_late_AP_Ca_T": np.c_[a[:, 3:6], early, late],
    }


def fit_predict(xtrain: np.ndarray, ytrain: np.ndarray, xtest: np.ndarray) -> np.ndarray:
    """Fixed-bandwidth RBF kernel ridge; hyperparameters never use held-out data."""
    mu = xtrain.mean(axis=0)
    sd = xtrain.std(axis=0)
    keep = sd > 1e-10
    if not keep.any():
        return np.repeat(ytrain.mean(axis=0, keepdims=True), len(xtest), axis=0)
    x = (xtrain[:, keep] - mu[keep]) / sd[keep]
    z = (xtest[:, keep] - mu[keep]) / sd[keep]
    train_sq = cdist(x, x, "sqeuclidean")
    nz = train_sq[train_sq > 1e-12]
    scale = float(np.median(nz)) if nz.size else 1.0
    kernel = np.exp(-train_sq / scale)
    cross = np.exp(-cdist(z, x, "sqeuclidean") / scale)
    ym = ytrain.mean(axis=0)
    weights = np.linalg.solve(kernel + 0.02 * np.eye(len(x)), ytrain - ym)
    return ym + cross @ weights


def run() -> None:
    a = np.loadtxt(DATA, delimiter=",")
    assert a.shape[1] == 42 and np.isfinite(a).all()
    xsets = feature_sets(a)
    theta = a[:, :3]
    target = a[:, 30:42]
    # Target is an unobserved 225-ms, 1.075 stretch pulse.
    # ΔAPD, max voltage deflection, min free-Ca deflection,
    # tension 20 ms after onset, voltage/Ca 20 ms after onset.
    ycols = [0, 2, 3, 6, 8, 10]
    ynames = ["delta_APD_ms", "max_delta_Vm_mV", "min_delta_Ca_uM",
              "Ta_20ms_kPa", "delta_Vm_20ms_mV", "delta_Ca_20ms_uM"]
    y = target[:, ycols]
    theta_scale = np.array([1.5, 4.0, 0.7])
    yscale = np.maximum(y.std(axis=0), 1e-9)
    results = {}
    n = len(a)
    for noise_fraction in [0.0, 0.02, 0.10]:
        for label, xfull in xsets.items():
            p_errors, y_errors = [], []
            for seed in range(20):
                rng = np.random.default_rng(10000 + seed)
                order = rng.permutation(n)
                ntest = max(8, n // 4)
                test, train = order[:ntest], order[ntest:]
                # Input noise is scaled to synthetic population variability,
                # not claimed to match experimental acquisition noise.
                noise_sd = noise_fraction * xfull.std(axis=0)
                xtrain = xfull[train] + rng.normal(size=(len(train), xfull.shape[1])) * noise_sd
                xtest = xfull[test] + rng.normal(size=(len(test), xfull.shape[1])) * noise_sd
                theta_pred = fit_predict(xtrain, theta[train], xtest)
                y_pred = fit_predict(xtrain, y[train], xtest)
                p_errors.append(np.abs(theta_pred - theta[test]))
                y_errors.append(np.abs(y_pred - y[test]))
            pe = np.concatenate(p_errors)
            ye = np.concatenate(y_errors)
            results[f"{label}|noise_{noise_fraction:g}"] = {
                "parameter_MAE": dict(zip(["g_ionic", "beta1", "Tref_scale"], pe.mean(axis=0).tolist())),
                "parameter_normalized_MAE": float(np.mean(pe / theta_scale)),
                "target_MAE": dict(zip(ynames, ye.mean(axis=0).tolist())),
                "target_standardized_MAE": float(np.mean(ye / yscale)),
                "n_cell": n,
                "n_splits": 20,
                "heldout_cells_per_split": ntest,
            }
    payload = {
        "methods": "Fixed RBF kernel ridge; 20 repeated 75/25 held-out-cell splits. The repeated splits are not independent biological replicates.",
        "forward": "ToR-ORd/SAC plus Land2016 with dynamic TnC; same equations used to generate training and test virtual cells.",
        "challenge": "Early 150 ms lambda 1.10; late 600 ms lambda 1.10; blind target 225 ms lambda 1.075; 1 ms ramp, 10 ms hold, 1 ms release.",
        "noise": "Zero and independent Gaussian feature noise at 2% of cohort feature SD; this is a robustness probe, not a calibrated experimental noise model.",
        "ranges": {"g_ionic": [0.25, 1.75], "beta1": [-4.5, -0.5], "Tref_scale": [0.65, 1.35]},
        "target_population_SD": dict(zip(ynames, y.std(axis=0).tolist())),
        "results": results,
    }
    OUT.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    # A single preregistered split for a separate native-ODE closure check.
    rng = np.random.default_rng(777)
    order = rng.permutation(n)
    check_test, check_train = order[:12], order[12:]
    check_x = xsets["early_AP_Ca_T"]
    inferred = fit_predict(check_x[check_train], theta[check_train], check_x[check_test])
    inferred = np.clip(inferred, [0.25, -4.5, 0.65], [1.75, -0.5, 1.35])
    direct = fit_predict(check_x[check_train], y[check_train], check_x[check_test])
    np.savetxt(TWIN_INPUT,
               np.c_[check_test + 1, theta[check_test], inferred, y[check_test], direct],
               delimiter=",", fmt="%.12g",
               header="cell_index,g_true,beta1_true,tref_true,g_est,beta1_est,tref_est,"
                      + ",".join("true_" + q for q in ynames) + ","
                      + ",".join("direct_" + q for q in ynames), comments="")
    for key, val in results.items():
        print(key, "param", round(val["parameter_normalized_MAE"], 4),
              "target", round(val["target_standardized_MAE"], 4),
              "g", round(val["parameter_MAE"]["g_ionic"], 4),
              "beta", round(val["parameter_MAE"]["beta1"], 4))
    print("saved", OUT)
    print("saved", TWIN_INPUT)


if __name__ == "__main__":
    run()
